using System.Security.Cryptography;
using System.Text.Json;
using System.Text.Json.Nodes;

namespace VoicemeeterBridge.Configuration;

/// <summary>
/// Makes sure the per-user override file holds an auth token, generating one on first run.
/// </summary>
public static class TokenStore
{
    /// <summary>
    /// Reads <c>Bridge:Token</c> from <paramref name="overridePath"/>. When the file or the
    /// value is missing a random token is generated and written back.
    /// </summary>
    /// <param name="overridePath">Full path of the user's <c>appsettings.json</c> override.</param>
    /// <returns>The token and whether it was generated by this call.</returns>
    /// <exception cref="InvalidDataException">The override file exists but is not valid JSON.</exception>
    public static (string Token, bool Generated) EnsureToken(string overridePath)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(overridePath);

        JsonObject root;
        if (File.Exists(overridePath))
        {
            try
            {
                root = JsonNode.Parse(File.ReadAllText(overridePath)) as JsonObject
                    ?? throw new InvalidDataException($"'{overridePath}' must contain a JSON object.");
            }
            catch (JsonException ex)
            {
                throw new InvalidDataException($"'{overridePath}' is not valid JSON: {ex.Message}", ex);
            }
        }
        else
        {
            root = new JsonObject();
        }

        if (root["Bridge"] is not JsonObject bridge)
        {
            bridge = new JsonObject();
            root["Bridge"] = bridge;
        }

        if (bridge["Token"]?.GetValue<string>() is { Length: > 0 } existing)
        {
            return (existing, false);
        }

        var token = GenerateToken();
        bridge["Token"] = token;
        Directory.CreateDirectory(Path.GetDirectoryName(overridePath)!);
        File.WriteAllText(overridePath, root.ToJsonString(new JsonSerializerOptions { WriteIndented = true }));
        return (token, true);
    }

    /// <summary>Creates a 32 character hexadecimal token from 16 random bytes.</summary>
    public static string GenerateToken() => Convert.ToHexStringLower(RandomNumberGenerator.GetBytes(16));
}
